import { readFileSync } from 'node:fs';
import { join } from 'node:path';
import { describe, expect, it } from 'vitest';
import { REPLY_TONES } from '@tp/shared/summary';
import { ALL_CATALOGUES as messages } from '../../lib/messages/all.js';
import { sourceFiles } from '../../lib/source-files.js';
import { IDLE, applyEvent, type ReplyState } from './reply-job.js';

const ROOT = new URL('../../', import.meta.url).pathname.replace(/^\/([A-Za-z]:)/, '$1');

describe('the reply helper keeps what it holds on this computer', () => {
  const HOLDS_TEXT = [
    'screens/send/ReplyHelp.tsx',
    'screens/send/ReplyPanel.tsx',
    'screens/send/reply-job.ts',
    'lib/ai-bridge.ts',
  ];

  it.each(HOLDS_TEXT)('%s never talks to the server and never stores a text', (name) => {
    const source = readFileSync(join(ROOT, name), 'utf8');
    expect(source).not.toMatch(
      /lib\/api|fetch\(|XMLHttpRequest|sendBeacon|WebSocket|localStorage|sessionStorage|indexedDB|document\.cookie/,
    );
  });

  it('is loaded on demand, and only the two Send screens reach for it', () => {
    expect(readFileSync(join(ROOT, 'screens/send/ReplyHelp.tsx'), 'utf8')).toMatch(
      /lazy\(\(\) => import\('\.\/ReplyPanel\.js'\)\)/,
    );
    const offenders = sourceFiles(ROOT)
      .filter((path) => !/[\\/]Reply(Help|Panel)\.tsx$/.test(path))
      .filter((path) => /(\.|send)\/Reply(Help|Panel)\.js/.test(readFileSync(path, 'utf8')))
      .map((path) => path.slice(ROOT.length).replaceAll('\\', '/'));
    expect(offenders.sort()).toEqual(['screens/send/Send.tsx', 'screens/send/SendCampaign.tsx']);
  });

  it('never sends: it imports no sending call and queues nothing', () => {
    for (const name of HOLDS_TEXT) {
      expect(readFileSync(join(ROOT, name), 'utf8'), name).not.toMatch(
        /sendDocument|sendBatch|sendCampaign|client\./,
      );
    }
  });
});

describe('the words of the reply helper', () => {
  it('exist for every tone, in every language', () => {
    for (const [code, catalogue] of Object.entries(messages)) {
      for (const tone of REPLY_TONES) {
        expect(catalogue[`reply.tone.${tone}`], `${code} ${tone}`).toBeTruthy();
      }
    }
  });

  it('keep the same fill-ins in every language', () => {
    const fills = (text: string) => (text.match(/\{\w+\}/g) ?? []).sort().join();
    for (const key of ['reply.warn.numbers', 'reply.placeholders'] as const) {
      const english = fills(messages['en-GB']![key]);
      expect(english).not.toBe('');
      for (const [code, catalogue] of Object.entries(messages)) {
        expect(fills(catalogue[key]), `${code} ${key}`).toBe(english);
      }
    }
  });

  it('say, in the draft label, that the model is on this computer and to check it', () => {
    expect(messages['en-GB']!['reply.label']).toBe(
      'Generated by the model on this computer — check it before using',
    );
  });
});

describe("a reply task's events", () => {
  it('stream text, end with warnings, or end with a problem', () => {
    let state: ReplyState = { ...IDLE, phase: 'running' };
    state = applyEvent(state, { id: 'a', kind: 'step', step: 'writing', done: 0, total: 1 });
    state = applyEvent(state, { id: 'a', kind: 'text', mode: 'replace', text: 'Hel' });
    state = applyEvent(state, { id: 'a', kind: 'text', mode: 'append', text: 'lo' });
    expect(state.text).toBe('Hello');
    expect(state.step).toEqual({ step: 'writing', done: 0, total: 1 });
    const done = applyEvent(state, {
      id: 'a',
      kind: 'done',
      warnings: [{ kind: 'repetition' }],
      seconds: 1,
    });
    expect(done).toMatchObject({ phase: 'done', text: 'Hello', step: null });
    expect(done.warnings).toEqual([{ kind: 'repetition' }]);
    expect(applyEvent(state, { id: 'a', kind: 'error', problem: 'cancelled' })).toMatchObject({
      phase: 'failed',
      problem: 'cancelled',
    });
    expect(applyEvent(state, { id: 'a', kind: 'queued', position: 1 })).toBe(state);
  });
});
